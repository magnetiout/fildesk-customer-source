#!/usr/bin/env python3
"""Validate one public configuration and emit the Rust build-time policy."""
import argparse, base64, ipaddress, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
def validate(c):
    if set(c) != {'environment','profile','id_server','relay_server','public_key'}:
        raise ValueError('Only environment/profile/id_server/relay_server/public_key are allowed')
    if c['environment'] not in ('development','staging','production') or c['profile'] not in ('customer','operator'):
        raise ValueError('Invalid environment/profile')
    for k in ('id_server','relay_server'):
        value = c[k]
        if not isinstance(value,str) or not re.fullmatch(r'[a-zA-Z0-9.-]+:[0-9]{1,5}',value):
            raise ValueError(f'{k}: explicit host:port required (IPv4/FQDN)')
        host, port = value.rsplit(':',1)
        if not 1 <= int(port) <= 65535 or '..' in host or host.startswith(('.', '-')):
            raise ValueError('Invalid host or port')
        if c['environment'] == 'production':
            if host in ('localhost',) or host.endswith(('.test','.invalid','.example','.local')) or host in ('example.com','example.org'):
                raise ValueError('Production requires a real hostname')
            try:
                addr = ipaddress.ip_address(host)
            except ValueError:
                if '.' not in host: raise ValueError('Production requires FQDN')
            else:
                if not addr.is_global: raise ValueError('Production cannot use non-global IP')
    try:
        key = base64.b64decode(c['public_key'],validate=True)
    except Exception as e:
        raise ValueError('Invalid public key') from e
    if len(key) != 32 or not any(key): raise ValueError('Expected a 32-byte Ed25519 PUBLIC key')
    if c['environment'] == 'production':
        known = ROOT/'config/development-public-keys.json'
        if known.exists() and c['public_key'] in json.loads(known.read_text()):
            raise ValueError('Known development key forbidden in production')
        dev = ROOT/'deployment/development/data/id_ed25519.pub'
        if dev.exists() and dev.read_text().strip() == c['public_key']:
            raise ValueError('Development key forbidden in production')
    return c

def render(c):
    c = validate(c)
    name = 'FilDesk' + {'development':'-Dev','staging':'-Staging','production':''}[c['environment']]
    if c['profile']=='operator': name += '-Operator'
    values = {'APP_NAME':name,'ID_SERVER':c['id_server'],'RELAY_SERVER':c['relay_server'], 'PUBLIC_KEY':c['public_key'], 'PROFILE':c['profile'], 'ENVIRONMENT':c['environment']}
    return '// Generated by scripts/configure-client.py; public values only.\n' + ''.join(f'pub const {k}: &str = {json.dumps(v)};\n' for k,v in values.items())

if __name__=='__main__':
    p=argparse.ArgumentParser(); p.add_argument('config',type=pathlib.Path); a=p.parse_args()
    config=json.loads(a.config.read_text())
    result=render(config)
    if config['environment'] in ('development','staging'):
        registry=ROOT/'config/development-public-keys.json'
        known=json.loads(registry.read_text()) if registry.exists() else []
        registry.write_text(json.dumps(sorted(set(known+[config['public_key']])),indent=2)+'\n')
    (ROOT/'client/src/fil_build_config.rs').write_text(result)
    print('Validated public configuration generated; no private key accepted.')
